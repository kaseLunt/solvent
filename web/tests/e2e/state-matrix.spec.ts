/**
 * Every route the Scenarios page can issue, by glob, from the demo dataset
 * (the shape of tests/e2e/lab.spec.ts's mockLab). One-address mode is the
 * Inspector's reading, so the Inspector's routes are served beside the listing.
 * `*` never crosses `/`, so the listing route does not swallow the run route.
 */
async function mockLab(page: Page, m: LabMocks = {}): Promise<void> {
  await page.route("**/v1/meta*", (route) => fulfillJson(route, DEMO_META));
  await page.route("**/v1/evidence*", (route) => fulfillJson(route, EVIDENCE_MANIFEST));
  await page.route("**/v1/params*", (route) => fulfillJson(route, DEMO_PARAMS_DM));
  await page.route("**/v1/events*", (route) => fulfillJson(route, DEMO_EVENTS_NEAR));
  await page.route("**/v1/address/*/history*", (route) => fulfillJson(route, DEMO_HISTORY_NEAR));
  await page.route("**/v1/address/*/stress*", (route) =>
    fulfillJson(route, m.stress ?? DEMO_STRESS_NEAR, m.stressStatus ?? 200),
  );
  await page.route("**/v1/address/*", (route) => fulfillJson(route, m.address ?? DEMO_ADDRESS_NEAR));
  await page.route("**/v1/scenarios/*/run-book", (route) =>
    route.request().method() === "OPTIONS"
      ? route.fulfill({ status: 204, headers: RUN_CORS, body: "" })
      : route.fulfill({
          status: m.runBookStatus ?? 200,
          headers: RUN_CORS,
          contentType: "application/json",
          body: JSON.stringify(m.runBook ?? DEMO_RUN_BOOK_ETH),
        }),
  );
  await page.route("**/v1/scenarios", (route) => fulfillJson(route, m.scenarios ?? DEMO_SCENARIOS));
}

