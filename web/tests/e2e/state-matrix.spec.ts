//   - NULL never renders 0 ("the most dangerous zero");
//   - refused/withheld rows stay VISIBLE and COUNTED, never dropped;
//   - no fake freshness — every as-of is the wire's own statement;
//   - `found: null` NEVER renders "no position";
//   - live posture is never conflated with history;
//   - every chart states its as-of;
//   - severity is color AND form, never hue alone.
//
// EXTENDING: a new surface or state is ONE row in `MATRIX` — give it a
// surface, a state name, its mocked routes, an optional `act`, and the law
// assertions for that cell. The driver loop at the bottom does the rest.
//
